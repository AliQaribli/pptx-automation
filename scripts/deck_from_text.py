"""Turn a plain-text topic into a finished PPTX using the local engine.

Prints exactly one line: DECK:<absolute path to deck.pptx>
No network, no credentials, no interactive prompts.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TEMPLATE = ROOT / "examples" / "brief.json"


def slugify(text: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    slug = slug[:32] or "deck"
    digest = hashlib.sha1(text.encode("utf-8")).hexdigest()[:8]
    return f"{slug}-{digest}"


def _placeholder(caption: str, layout: str = "right") -> dict:
    return {
        "path": "__placeholder__",
        "credit": "Original illustration",
        "caption": caption,
        "layout": layout,
    }


def build_brief(topic: str) -> dict:
    brief = json.loads(TEMPLATE.read_text(encoding="utf-8"))
    words = " ".join(topic.split())
    label = " ".join(words.split()[:8])[:60]
    brief["meta"]["title"] = label
    brief["meta"]["subtitle"] = "Generated by Beautiful Deck Agent"
    slides = brief["slides"]
    # Keep visible text short so non-Latin and very long topics still pass QA.
    slides[0]["kicker"] = label
    slides[0]["title"] = "Here is what matters most"
    slides[0]["body"] = [f"About {label}."]
    slides[1]["title"] = "Three ideas explain the shift"
    slides[2]["title"] = "The numbers point one way"
    slides[3]["title"] = "The trade-offs are real"
    slides[4]["title"] = "Adoption is gaining ground"
    slides[5]["title"] = "The next move needs an owner"
    slides[0]["image"] = _placeholder("Visual", "right")
    slides[4]["image"] = _placeholder("Where it grows", "full")
    slides[5]["image"] = _placeholder("Next steps", "right")
    slides[-1]["sources"] = [{"label": f"Brief: {label}", "url": ""}]
    return brief


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("topic", help="plain-text presentation topic")
    parser.add_argument("--out", default=None, help="output directory")
    args = parser.parse_args()

    topic = " ".join(args.topic.split()).strip()
    if not topic:
        print("ERROR: empty topic", file=sys.stderr)
        return 2

    out_dir = Path(args.out).resolve() if args.out else ROOT / "output" / "telegram" / slugify(topic)
    out_dir.mkdir(parents=True, exist_ok=True)
    brief_path = out_dir / "brief.json"
    brief_path.write_text(json.dumps(build_brief(topic), indent=2, ensure_ascii=False), encoding="utf-8")

    result = subprocess.run(
        [sys.executable, "-m", "presentation.cli", str(brief_path), "--out", str(out_dir)],
        cwd=str(ROOT),
        capture_output=True,
        text=True,
        timeout=180,
    )
    if result.returncode != 0:
        print((result.stdout + result.stderr).strip(), file=sys.stderr)
        return result.returncode

    deck = out_dir / "deck.pptx"
    if not deck.exists():
        print("ERROR: engine did not produce deck.pptx", file=sys.stderr)
        return 3
    print(f"DECK:{deck}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
